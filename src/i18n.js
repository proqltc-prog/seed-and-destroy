export function isLanguage(code) {
  return LANGUAGES.some((l) => l.code === code);
}

// Best supported language for a browser language like "de-BE".
export function detectLanguage(browserLanguage) {
  const code = String(browserLanguage ?? '').slice(0, 2).toLowerCase();
  return isLanguage(code) ? code : FALLBACK_LANGUAGE;
}

// Text for key in the language, with {placeholders} filled in. Falls back
// to English, then to the key itself.
export function t(lang, key, vars = {}) {
  const text = STRINGS[lang]?.[key] ?? STRINGS[FALLBACK_LANGUAGE][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}

// Numbers the way the language writes them: 25.000, 25 000, 25,000 ...
export function formatNumber(lang, n) {
  return new Intl.NumberFormat(lang).format(n);
}
